-- V9017：车辆对象标识格式放宽（兼容车辆 ID 与历史车牌号）
--
-- 背景：V6 曾将车辆标识定为车牌号（id_pattern 为车牌正则）。业务口径澄清：
--       写入/查询的 object_id 应为「车辆 ID」（车联网内部唯一编号），车牌号放 object_name。
--       为兼容存量（历史演示数据/已接入方仍以车牌作为 object_id），校验放宽为二者兼容：
--       - 车牌号：省份简称(1 汉字) + 字母 + 5~6 位字母/数字（普通 7 位 / 新能源 8 位）
--       - 车辆 ID：字母/数字/下划线/中划线，4~64 位（如 VH10086、CL-2026-0001）
-- 影响：写入校验、画像查询、任务对象校验对所有 vehicle 对象生效；
--       同一对象仍须保持单一标识口径（object_id 是幂等/频控/任务匹配键）。
-- ============================================================================
UPDATE object_type_meta
SET id_pattern = '^(?:[一-龥][A-Z][A-Z0-9]{5,6}|[A-Za-z0-9_-]{4,64})$'
WHERE object_type = 'vehicle';
