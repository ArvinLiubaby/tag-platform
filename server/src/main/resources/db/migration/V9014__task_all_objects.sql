-- ============================================================================
-- 打标任务「全部对象」模式（tag_task.all_objects）
-- 背景：选择「全部对象」创建任务时，不校验对象索引是否为空、也不要求对象已存在；
--       任务发布后，外部推送进来的任意对象自动纳入任务项并接收打标。
-- 取值：0=指定对象（默认，沿用原逻辑）；1=全部对象模式
-- ============================================================================

ALTER TABLE tag_task
  ADD COLUMN all_objects TINYINT NOT NULL DEFAULT 0 COMMENT '1=全部对象模式（写入时自动纳入新对象）';
