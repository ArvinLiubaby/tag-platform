-- ============================================================================
-- V9018：对象索引增加对象名称（object_index.object_name）
--
-- 背景：画像查询结果与对象下拉需要展示「司机姓名 / 车辆车牌号」等可读名称，
--       名称属于对象级属性（写入时 items[].object_name 提供），此前只落在值流水
--       （tag_value_history.object_name），画像与下拉无法直接读取。
-- 影响：object_index 新增可空列；写入受理后由 ObjectIndexHook 登记/更新（仅在有值时覆盖）。
-- ============================================================================
ALTER TABLE object_index ADD COLUMN object_name VARCHAR(256) COMMENT '对象名称（司机姓名/车牌号等，展示用；随写入更新）';
