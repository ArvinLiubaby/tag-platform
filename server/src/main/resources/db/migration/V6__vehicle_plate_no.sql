-- ============================================================================
-- V6：车辆对象标识由 VIN 切换为车牌号（业务口径调整）
--
-- 背景：客服/风控业务按车牌号识别车辆（如 苏A88888），VIN 不适合作为业务输入。
-- 规则：省份简称(1 个汉字) + 字母 + 5~6 位字母/数字；
--       普通车牌 7 位（苏A88888），新能源 8 位（苏AD12345）。
-- 影响：新契约下 vehicle 的写入与查询 object_id 均须使用车牌号；
--       存量 VIN 形态的标签值保留在库中（历史数据不删除），但不再通过新校验。
-- ============================================================================
UPDATE object_type_meta
SET id_field = 'plate_no',
    id_pattern = '^[一-龥][A-Z][A-Z0-9]{5,6}$'
WHERE object_type = 'vehicle';
