-- ============================================================================
-- 统计指标单位（tag_meta.unit / tag_meta_version.unit）
-- 背景：日均时长（小时）、月均驾驶天数（天）、日均超速次数（次）等统计类标签
--       需要把计量单位作为定义的一部分返回给控制台与开放接口。
-- 约定：仅统计/数值类指标填写；文本、布尔、枚举类标签通常为空。
-- ============================================================================

ALTER TABLE tag_meta ADD COLUMN unit VARCHAR(16) COMMENT '计量单位（如 小时/天/次/公里），非数值指标为空';
ALTER TABLE tag_meta_version ADD COLUMN unit VARCHAR(16) COMMENT '计量单位（定义快照）';
